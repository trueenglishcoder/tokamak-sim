def vacuum_chamber_names() -> tuple[str, ...]:
    """Вернуть имена поддерживаемых вакуумных камер."""
    return tuple(sorted(_VACUUM_CHAMBERS))


def get_vacuum_chamber_shape(name: str | None) -> np.ndarray | None:
    """Вернуть копию именованного контура вакуумной камеры или None."""
    if name is None:
        return None
    key = str(name).upper()
    if key not in _VACUUM_CHAMBERS:
        choices = ", ".join(vacuum_chamber_names())
        raise ValueError(
            f"Unknown vacuum chamber {name!r}. "
            f"Available vacuum chambers: {choices}"
        )
    return _VACUUM_CHAMBERS[key].copy()
